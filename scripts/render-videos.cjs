// Renders one looping MP4 per exercise from the same animation code the app uses.
// Needs: node, ffmpeg, and the packages typescript, react, react-dom, sharp.
// Run:   node scripts/render-videos.cjs   (writes public/animations/<exercise-id>.mp4 and src/data/videos.js)
const fs = require('fs'), path = require('path'), os = require('os');
const { execFileSync } = require('child_process');
const { pathToFileURL } = require('url');
const ts = require('typescript'), React = require('react'), { renderToStaticMarkup } = require('react-dom/server'), sharp = require('sharp');

const FRAMES = 96, FPS = 24, W = 360, H = 406;
const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;');

(async () => {
  const root = path.resolve(__dirname, '..');
  const code = ts.transpileModule(fs.readFileSync(path.join(root, 'src/components/ExerciseFigure.jsx'), 'utf8'),
    { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, target: ts.ScriptTarget.ES2019 } }).outputText;
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fig-'));
  fs.writeFileSync(path.join(tmp, 'fig.cjs'), code);
  const { Figure, SPEC, equipOf } = require(path.join(tmp, 'fig.cjs'));
  const { EXERCISES } = await import(pathToFileURL(path.join(root, 'src/data/exercises.js')).href);
  const out = path.join(root, 'public/animations');
  fs.mkdirSync(out, { recursive: true });
  const ids = Object.keys(EXERCISES);
  for (const id of ids) {
    if (!SPEC[id]) throw new Error('No animation spec for ' + id);
    const dir = path.join(tmp, id);
    fs.mkdirSync(dir);
    for (let k = 0; k < FRAMES; k++) {
      const inner = renderToStaticMarkup(React.createElement(Figure, { id, t: (k / FRAMES) * 2 })).replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -26 200 226" width="${W}" height="${H}"><rect x="0" y="-26" width="200" height="226" fill="#0b0c10"/><text x="10" y="-9" font-family="DejaVu Sans, Arial, sans-serif" font-size="9.5" font-weight="700" fill="#F4EDE0">${esc(EXERCISES[id].name)}</text><text x="190" y="-9" text-anchor="end" font-family="DejaVu Sans, Arial, sans-serif" font-size="7.5" fill="#FF6B5B">${esc(equipOf(id))}</text>${inner}</svg>`;
      await sharp(Buffer.from(svg)).png().toFile(path.join(dir, String(k).padStart(4, '0') + '.png'));
    }
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-framerate', String(FPS), '-i', path.join(dir, '%04d.png'), '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-crf', '27', '-preset', 'veryfast', '-movflags', '+faststart', path.join(out, id + '.mp4')]);
    fs.rmSync(dir, { recursive: true });
    process.stdout.write(id + ' ');
  }
  fs.writeFileSync(path.join(root, 'src/data/videos.js'),
    `// One looping animation video per exercise id (generated by scripts/render-videos.cjs).\n// Replace any file in public/animations with real footage using the same name.\nconst FILES = ${JSON.stringify(ids)};\nexport const VIDEOS = (typeof window !== 'undefined' && window.__VIDEOS) || Object.fromEntries(FILES.map((id) => [id, \`/animations/\${id}.mp4\`]));\n`);
  console.log('\ndone', ids.length);
})();
